library;

// -----------------------------------------------------------------------------
// GRIECHISCH NORMALISIEREN – DISPLAY
// -----------------------------------------------------------------------------

String normalizeGreekForDisplay(String text) {
  return text
      .replaceAll('ᾰ', 'α')
      .replaceAll('ᾱ', 'α')
      .replaceAll('ῐ', 'ι')
      .replaceAll('ῑ', 'ι')
      .replaceAll('ῠ', 'υ')
      .replaceAll('ῡ', 'υ');
}

